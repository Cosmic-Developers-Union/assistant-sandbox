// Registered 返回已登记的系统调用(按编号排序),供能力查询、
// 追踪清单与差分执行器枚举使用。
func Registered() []Syscall {
	out := make([]Syscall, 0, len(handled))
	for call := range handled {
		out = append(out, call)
	}
	slices.Sort(out)
	return out
}

// IsRegistered 报告系统调用是否已登记:未登记调用在 Handle 中统一
// ENOSYS,差分执行器与追踪层可据此判定实现状态。
func IsRegistered(call Syscall) bool { return handled[call] }
